def _clean_city(value: str | None) -> str:
    return re.sub(r"(市|省|区|县|自治州|地区)$", "", (value or "").strip())


def _body_lines(content: str | None) -> list[str]:
    out = []
    for raw in (content or "").split("\n"):
        line = raw.strip()
        if not line:
            continue
        if line.startswith(INTRO_PREFIXES) or line.startswith(REMIND_PREFIXES):
            continue
        out.append(line)
    return out


def _header(memory: Memory, loc: Location | None, costs: list[dict], foreign: bool) -> str:
    date = (memory.happened_at or "")[:10]
    city = _clean_city(loc.city if loc else None)
    place = (loc.name or "").strip() if loc else ""
    if city and place and city != place:
        where = f"{city} · {place}"
    else:
        where = place or city

    bits = [b for b in (date, where) if b]
    total = 0
    if not foreign:
        for c in costs:
            amount = c.get("amount")
            if isinstance(amount, (int, float)):
                total += amount
    if total:
        bits.append(f"花销 ¥{int(total)}")
    return "先说数：" + "，".join(bits) + "。"


def _costs_json(items: list[tuple[str, float | None]] | None) -> str | None:
    if not items:
        return None
    return json.dumps(
        [{"label": label, "amount": amount, "note": None} for label, amount in items],
        ensure_ascii=False,
    )


def main() -> None:
    init_db()
    db = SessionLocal()
    try:
        done = 0
        missing = []
        for memory_id, spec in NODES.items():
            memory = db.get(Memory, memory_id)
            if not memory:
                missing.append(memory_id)
                continue
            loc = db.get(Location, memory.location_id) if memory.location_id else None

            body = spec.get("body")
            if body is None:
                body_lines = _body_lines(memory.content)
            else:
                body_lines = _body_lines(body)

            foreign = memory_id in FOREIGN_NODES or any(
                flag in json.dumps(spec.get("costs") or [], ensure_ascii=False)
                for flag in FOREIGN_FLAGS
            )
            if "costs" in spec:
                costs = [{"label": l, "amount": a} for l, a in spec["costs"]]
                memory.cost_json = _costs_json(spec["costs"])
            else:
                try:
                    costs = json.loads(memory.cost_json or "[]")
                except Exception:
                    costs = []

            head = _header(memory, loc, costs, foreign)
            walk = spec["walk"]
            memory.content = "\n".join([head, walk, *body_lines])
            memory.summary = "\n".join(body_lines) if body_lines else walk

            if spec.get("tips"):
                memory.tips = spec["tips"]
            if spec.get("transport"):
                memory.transport_info = spec["transport"]
            if spec.get("stay"):
                memory.stay_info = spec["stay"]
            done += 1

        db.commit()
        print(f"[完成] 重写了 {done} 个地图节点的写法")
        if missing:
            print(f"[注意] 这些记忆 id 没找到，已跳过：{missing}")
    finally:
        db.close()


if __name__ == "__main__":
    main()
