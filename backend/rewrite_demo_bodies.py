def main() -> None:
    init_db()
    db = SessionLocal()
    try:
        done = 0
        for title, body in BODIES.items():
            memory = db.query(Memory).filter(Memory.title == title).first()
            if not memory:
                print(f"（没这条，跳过）{title}")
                continue
            memory.summary = body.split("\n")[0]
            memory.content = body
            done += 1
        db.commit()
        print(f"[完成] {done} 条演示记忆的正文已补成攻略口吻")
    finally:
        db.close()


if __name__ == "__main__":
    main()
