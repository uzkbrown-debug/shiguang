def lookup_coords(name: str) -> tuple[float, float] | None:
    """按城市名查坐标；支持"东京都""京都市"这类带后缀的写法"""
    if not name:
        return None
    key = name.strip()
    if key in CITY_COORDS:
        return CITY_COORDS[key]

    # 去掉常见行政区后缀再试
    for suffix in ("市", "县", "省", "都", "区", "町", "村", "府"):
        if key.endswith(suffix):
            trimmed = key[: -len(suffix)]
            if trimmed in CITY_COORDS:
                return CITY_COORDS[trimmed]

    # 包含关系（例如「东京·涩谷」）
    for city, coords in CITY_COORDS.items():
        if len(city) >= 2 and city in key:
            return coords

    return None
