_SUFFIXES = ("特别行政区", "自治区", "自治州", "市辖区", "省", "市")

# 高德返回的层级里，这些算「城市」；district 也放行（浦东新区、鼓浪屿这种）
_OK_LEVELS = {"country", "province", "city", "district"}


def _norm(raw: str) -> str:
    name = _JUNK.sub("", raw or "").strip()
    name = re.sub(r"\s+", "", name)
    for suf in _SUFFIXES:
        if name.endswith(suf) and len(name) > len(suf) + 1:
            name = name[: -len(suf)]
            break
    return name


def _query_amap(name: str) -> list[dict] | None:
    """问一次高德；None 表示这次没问出来（没 key、网络、限流都算）"""
    from geo import AMAP_KEY

    if not AMAP_KEY:
        return None
    query = urllib.parse.urlencode(
        {"keywords": name, "subdistrict": 0, "extensions": "base", "key": AMAP_KEY}
    )
    data = _get_json(f"{_DISTRICT_URL}?{query}")
    if not data or str(data.get("status")) != "1":
        return None
    rows = []
    for row in data.get("districts") or []:
        n = (row.get("name") or "").strip()
        if n:
            rows.append({"name": n, "level": row.get("level") or "city"})
    return rows


def _amap_lookup(name: str) -> list[dict] | None:
    """带缓存 + 一次重试。高德免费额度有 QPS 限制，连着问会被拒"""
    if name in _LOOKUP_CACHE:
        return _LOOKUP_CACHE[name]
    for attempt in range(2):
        rows = _query_amap(name)
        if rows is not None:
            _LOOKUP_CACHE[name] = rows
            return rows
        if attempt == 0:
            time.sleep(0.3)
    return None


def resolve_city(raw: str | None) -> tuple[str | None, str]:
    """城市名 → (标准写法, 状态)

    状态：ok / empty / unknown / unavailable
    """
    name = _norm(raw or "")
    if not name:
        return (None, "empty")
    if name in CITY_NAMES:
        return (name, "ok")

    rows = _amap_lookup(name)
    if rows is None:
        return (name, "unavailable")
    for row in rows:
        plain = _norm(row["name"])
        if row.get("level") not in _OK_LEVELS:
            continue
        if plain == name or plain in name or name in plain:
            return (plain or row["name"], "ok")
    return (name, "unknown")
